#!/usr/bin/env python3
"""Regenerates swift-server/Tools.swift (tool list + extension method names) from the Node reference server's tools/list."""
import json, subprocess, sys
M = {"tabs":"tabs","frames":"frames","new_tab":"new_tab","close_tab":"close_tab","activate_tab":"activate","fullpage_screenshot":"fullshot"}
p = subprocess.Popen(["node", "server/server.js"], stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, text=True)
def rpc(o): p.stdin.write(json.dumps(o) + "\n"); p.stdin.flush(); return json.loads(p.stdout.readline())
rpc({"jsonrpc":"2.0","id":1,"method":"initialize","params":{"protocolVersion":"2025-03-26","capabilities":{},"clientInfo":{"name":"gen","version":"1"}}})
p.stdin.write(json.dumps({"jsonrpc":"2.0","method":"notifications/initialized"}) + "\n"); p.stdin.flush()
tools = rpc({"jsonrpc":"2.0","id":2,"method":"tools/list"})["result"]["tools"]
p.kill()
methods = {t["name"]: M.get(t["name"][len("safari_"):], t["name"][len("safari_"):]) for t in tools}
out = '// Generated by tools/gen_tools.py from server/server.js - do not edit.\nlet toolsJSON = #"""\n' + json.dumps(tools, ensure_ascii=False) + '\n"""#\nlet methodFor: [String: String] = ' + '[' + ', '.join(json.dumps(k) + ': ' + json.dumps(v) for k, v in methods.items()) + ']\n'
open("swift-server/Tools.swift", "w").write(out); print(len(tools), "tools")
